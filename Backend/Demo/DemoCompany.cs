    // construction company really works:
    //   P1: the company's own 5 marla luxury house in Bahria Town Lahore. Plot bought, built,
    //       furnished and sold to Client 1. Finished about a month and a half ago.
    //   P2: a triple storey apartment building near the Eiffel Tower, Bahria Town Lahore, built on
    //       contract for Client 2. About 70% done, so Field View, attendance, requests and alerts are live.
    // Days are offsets from today (negative = in the past), so the demo always looks current.
    // People use generic names (Client 1, Mason 1, Labourer 1); materials use real market names
    // and mid-2026 Lahore rates.
