        public record ClientSeed(string Key, string Name, string Type, string Phone, string Cnic, string City, string Address);
        public record ProjectSeed(string Key, string Title, string Client, string Type, string Area, string Location,
            string Description, int Start, int End, string Status, decimal Budget);
        // Phases are numbered in list order within each project.
        public record PhaseSeed(string Project, string Name, int Progress);
        public record EmployeeSeed(string Name, string Designation, string City);
        // Daily workers are present on PresentPercent of the working days (Monday to Saturday, not on holidays).
        public record AssignmentSeed(string Employee, string Project, string WageType, decimal Wage, int Start, int? End, int PresentPercent);
        public record MaterialSeed(string Name, string Category, string Unit, int LowStock, string Status);
        public record PurchaseSeed(int Day, string Material, decimal Qty, decimal Rate);
        // The cost of an issue is the moving average at that moment, as in the Materials module.
        public record IssueSeed(int Day, string Material, string Project, int Phase, decimal Qty);
        public record ExpenseSeed(int Day, string Project, string Category, string Description, decimal Amount,
            bool Recoverable, int Phase, string? PaidTo);
        // A line is a share of the project budget, or bills a recoverable expense (by its description).
        public record InvoiceLineSeed(string Text, decimal? Share, int Phase, string? Expense);
        // A payment with no amount pays whatever is still due on the invoice.
        public record InvoicePaymentSeed(int Day, decimal? Amount, string Method);
        public record InvoiceSeed(string Project, int Issued, int Due, string Notes, InvoiceLineSeed[] Lines, InvoicePaymentSeed[] Payments);
        public record RequestSeed(double Day, string Project, int Phase, string Material, decimal Qty, string Status,
            string Note, string? ResolvedBy, string? ResolveNote, int? ResolvedDay);
        public record InquirySeed(double Day, bool Read, string Name, string Phone, string? Email, string Service, string Message);

